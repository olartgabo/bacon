#!/usr/bin/env node
// Derives every brand asset from design/bacon-source.svg so the logo
// geometry lives in exactly one file. Run after editing the source:
//
//   npm run brand
//
// Writes src/design/brand-paths.generated.ts (path data for the React
// brand components), the favicon (src/app/icon.svg), the apple touch icon
// (src/app/apple-icon.png), and the PWA icons in public/.

import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const source = fs.readFileSync(path.join(root, "design/bacon-source.svg"), "utf8");
const paths = [...source.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);

// Indexes into the source's <path> order. The source is a Figma export of
// the brand sheet; these are the large mark and the wordmark letters in the
// top-left lockup. The cream "counter" overlays (indexes 28–31) are skipped:
// the letter paths already cut their own counters, so the wordmark works on
// any background without them.
const MARK = { dot: 12, arcTop: 11, stripTop: 9, stripBottom: 7, arcBottom: 4 };
const WORDMARK = [3, 5, 10, 6, 8]; // B a c o n

// Bounding boxes in source coordinates, read off the path data.
const MARK_BOX = { x: 44, y: 45, w: 37.6, h: 45 };
const LOCKUP_BOX = { x: 44, y: 45, w: 137, h: 45 };

const INK = "#29292D";
const CREAM = "#FDF5EA";
const RED = "#D45545";

const mark = Object.fromEntries(Object.entries(MARK).map(([k, i]) => [k, paths[i]]));
const wordmark = WORDMARK.map((i) => paths[i]);

for (const [name, d] of Object.entries({ ...mark, ...wordmark })) {
  if (!d) throw new Error(`brand path "${name}" not found — did the source SVG change?`);
}

const ts = `// Generated by scripts/build-brand.mjs from design/bacon-source.svg. Do not edit.

export const MARK_BOX = ${JSON.stringify(MARK_BOX)} as const;
export const LOCKUP_BOX = ${JSON.stringify(LOCKUP_BOX)} as const;

export const MARK = ${JSON.stringify(mark, null, 2)} as const;

export const WORDMARK = ${JSON.stringify(wordmark, null, 2)} as const;
`;
fs.writeFileSync(path.join(root, "src/design/brand-paths.generated.ts"), ts);

/** The app icon: the mark in cream and red on an ink rounded square, the
 * same treatment as the dark tile on the brand sheet. */
function appIconSvg({ size, radius }) {
  const pad = 0.2;
  const scale = (size * (1 - 2 * pad)) / MARK_BOX.h;
  const tx = (size - MARK_BOX.w * scale) / 2 - MARK_BOX.x * scale;
  const ty = (size - MARK_BOX.h * scale) / 2 - MARK_BOX.y * scale;
  const fill = { dot: RED, arcTop: CREAM, stripTop: RED, stripBottom: RED, arcBottom: CREAM };
  const body = Object.entries(mark)
    .map(([k, d]) => `<path d="${d}" fill="${fill[k]}"/>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${INK}"/><g transform="translate(${tx.toFixed(3)} ${ty.toFixed(3)}) scale(${scale.toFixed(5)})">${body}</g></svg>\n`;
}

fs.writeFileSync(path.join(root, "src/app/icon.svg"), appIconSvg({ size: 32, radius: 7 }));

// iOS and Android mask their own corners, so the raster icons are full bleed.
const raster = [
  ["src/app/apple-icon.png", 180],
  ["public/icon-192.png", 192],
  ["public/icon-512.png", 512],
];
for (const [out, size] of raster) {
  await sharp(Buffer.from(appIconSvg({ size, radius: 0 })))
    .png()
    .toFile(path.join(root, out));
}

console.log("brand assets written");

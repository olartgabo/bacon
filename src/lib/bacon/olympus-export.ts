import { execFile } from "node:child_process";
import { promisify } from "node:util";
import fs from "node:fs";
import path from "node:path";
import { asc } from "drizzle-orm";
import type { Db } from "@/lib/db/client";
import { identities, taskEvents, tasks, type Identity, type Task, type TaskEvent } from "@/lib/db/schema";
import { CLOSED_STATUSES, SPACES, SPACE_LABEL, STATUS_LABEL } from "./model";
import { formatRef } from "./service";

const EXPORT_DIR = path.join("tasks", "bacon");

/** One line per event: the timeline reads as a log in olympus, and the
 * full text stays in bacon. */
function eventLine(e: TaskEvent, who: Map<number, Identity>): string {
  const actor = who.get(e.actorId)?.name ?? `#${e.actorId}`;
  const when = e.createdAt.slice(0, 16).replace("T", " ");
  const firstLine = (e.body ?? "").split("\n")[0].trim();
  const text = firstLine.length > 200 ? `${firstLine.slice(0, 199)}…` : firstLine;
  const url = e.type === "link" && typeof e.data?.url === "string" ? ` <${e.data.url}>` : "";
  return `- ${when} UTC · ${actor} · ${e.type}${text ? `: ${text}` : ""}${url}`;
}

export function renderTask(task: Task, events: TaskEvent[], who: Map<number, Identity>, baseUrl: string): string {
  const ref = formatRef(task.id);
  const name = (id: number | null) => (id === null ? "" : (who.get(id)?.name ?? `#${id}`));
  const front = [
    ["ref", ref],
    ["status", task.status],
    ["space", task.space ?? ""],
    ["priority", task.priority],
    ["due", task.due ?? ""],
    ["assignee", name(task.assigneeId)],
    ["created_by", name(task.createdById)],
    ["created_at", task.createdAt],
    ["updated_at", task.updatedAt],
  ]
    .filter(([, v]) => v !== "")
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join("\n");

  return `---
${front}
---

<!-- Generated by bacon. Edit at ${baseUrl}/t/${ref}, not here: this file is overwritten. -->

# ${ref}: ${task.title}

${task.body.trim() || "_No description._"}

## Timeline

${events.map((e) => eventLine(e, who)).join("\n") || "_No events._"}
`;
}

function renderIndex(all: Task[]): string {
  const open = all.filter((t) => !CLOSED_STATUSES.includes(t.status));
  const sections = [...SPACES, null].map((space) => {
    const rows = open.filter((t) => t.space === space);
    if (rows.length === 0) return "";
    const heading = space ? SPACE_LABEL[space] : "Inbox";
    const lines = rows.map((t) => `- [${formatRef(t.id)}](./${formatRef(t.id)}.md) · ${STATUS_LABEL[t.status]} · ${t.title}`);
    return `## ${heading}\n\n${lines.join("\n")}\n`;
  });
  return `<!-- Generated by bacon. Do not edit. -->

# Open tasks

bacon is the source of truth for tasks (decision 0005). This folder is a read-only snapshot.

${sections.filter(Boolean).join("\n") || "_Nothing open._\n"}`;
}

/** Writes every task file and the index. Returns true if anything changed
 * on disk; identical content is not rewritten, so mtimes stay put. */
export function writeSnapshot(db: Db, repo: string, baseUrl: string): boolean {
  const dir = path.join(repo, EXPORT_DIR);
  fs.mkdirSync(dir, { recursive: true });
  const who = new Map(db.select().from(identities).all().map((i) => [i.id, i]));
  const all = db.select().from(tasks).orderBy(asc(tasks.id)).all();
  const eventsByTask = new Map<number, TaskEvent[]>();
  for (const e of db.select().from(taskEvents).orderBy(asc(taskEvents.id)).all()) {
    eventsByTask.set(e.taskId, [...(eventsByTask.get(e.taskId) ?? []), e]);
  }

  let changed = false;
  const write = (file: string, content: string) => {
    const target = path.join(dir, file);
    if (fs.existsSync(target) && fs.readFileSync(target, "utf-8") === content) return;
    fs.writeFileSync(target, content);
    changed = true;
  };
  for (const task of all) {
    write(`${formatRef(task.id)}.md`, renderTask(task, eventsByTask.get(task.id) ?? [], who, baseUrl));
  }
  write("README.md", renderIndex(all));
  return changed;
}

const run = promisify(execFile);

// Async so a slow pull or push never blocks the server answering MCP calls.
const git = async (repo: string, ...args: string[]) => (await run("git", ["-C", repo, ...args])).stdout;

/** `git diff --quiet` exits 1 when there are differences. Any other
 * failure (not a repo, broken index) is a real error. */
async function hasStagedChanges(repo: string): Promise<boolean> {
  try {
    await git(repo, "diff", "--cached", "--quiet", "--", EXPORT_DIR);
    return false;
  } catch (err) {
    if ((err as { code?: unknown }).code === 1) return true;
    throw err;
  }
}

export type ExportResult = { committed: false } | { committed: true; sha: string };

/**
 * Pulls olympus, writes the snapshot, and commits and pushes it only when
 * the export folder actually changed. The checkout is bacon's own clone on
 * the host, so a fast-forward-only pull is enough; if it can't
 * fast-forward, the error surfaces instead of rewriting history.
 */
export async function exportToOlympus(
  db: Db,
  repo: string,
  opts: { baseUrl: string; push: boolean },
): Promise<ExportResult> {
  if (opts.push) await git(repo, "pull", "--ff-only", "--quiet");
  writeSnapshot(db, repo, opts.baseUrl);
  await git(repo, "add", "--", EXPORT_DIR);
  if (!(await hasStagedChanges(repo))) return { committed: false };
  await git(
    repo,
    "-c",
    "user.name=bacon",
    "-c",
    "user.email=bacon@tasks.olartgabo.dev",
    "commit",
    "--quiet",
    "-m",
    "bacon: export task snapshot",
    "--",
    EXPORT_DIR,
  );
  if (opts.push) await git(repo, "push", "--quiet", "origin", "HEAD");
  return { committed: true, sha: (await git(repo, "rev-parse", "--short", "HEAD")).trim() };
}
